"""
Groundedness audit: check generated marketing copy for unverifiable / fabricated claims.

Sends the copy to a large model with a strict instruction: flag any claim that could not
be substantiated, any invented statistic, any misleading capability claim, and any ASA/FTC
risk. This is the guardrail on LLM-generated sales copy.

Usage:
  python -m scripts.claims_audit --dir service_kit/<slug> --model gpt-oss:120b-cloud
"""
import argparse
import json
import urllib.request
from pathlib import Path

OLLAMA = "http://127.0.0.1:11434"

SYSTEM = """You are a UK advertising-standards (ASA/CAP) and FTC compliance auditor. You are
given marketing copy generated by an AI. Your ONLY job is to flag claims that are risky or
unverifiable. For EACH problem, output:
- QUOTE: the exact offending phrase
- TYPE: one of [UNVERIFIABLE FACTUAL CLAIM | INVENTED STATISTIC | MISLEADING CAPABILITY |
  COMPARATIVE CLAIM NEEDING EVIDENCE | AI-DISCLOSURE MISSING | TESTIMONIAL/RESULT NOT PROVEN |
  OK-NO-ISSUE]
- WHY: what rule or risk it breaches, in one sentence
- FIX: the safe rewritten version
Be strict. Mark any specific number, price comparison, speed claim, hosting/location claim,
environmental claim, or performance promise as needing evidence unless it is obviously the
operator's own published price. If the copy is clean, say so explicitly."""


def audit(text, model, num_predict=4000, timeout=600):
    payload = {
        "model": model,
        "messages": [{"role": "system", "content": SYSTEM},
                     {"role": "user", "content": f"Audit this marketing copy:\n\n{text}"}],
        "stream": False,
        "options": {"temperature": 0.1, "num_predict": num_predict},
    }
    req = urllib.request.Request(f"{OLLAMA}/api/chat",
                                 data=json.dumps(payload).encode(),
                                 headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        d = json.loads(r.read().decode())
    return d.get("message", {}).get("content", ""), d.get("done_reason")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", required=True)
    ap.add_argument("--model", default="gpt-oss:120b-cloud")
    ap.add_argument("--out", default=None)
    ap.add_argument("--num-predict", type=int, default=4000)
    a = ap.parse_args()

    d = Path(a.dir)
    files = sorted(d.glob("*.md"))
    combined = "\n\n".join(f"--- {f.name} ---\n{f.read_text()}" for f in files)
    print(f"Auditing {len(files)} files ({len(combined)} chars) with {a.model} ...")
    text, reason = audit(combined, a.model, a.num_predict)
    if not text.strip():
        print(f"REFUSED TO WRITE: model returned {len(text)} chars (done_reason={reason}).")
        print("Try gpt-oss:120b-cloud or mistral-large-3:675b-cloud, or raise --num-predict.")
        import sys; sys.exit(2)
    out = Path(a.out) if a.out else d / "CLAIMS_AUDIT.md"
    out.write_text(f"# Claims Audit ({a.model})\n\n{text}\n")
    print(f"done_reason={reason} chars={len(text)} -> {out}")


if __name__ == "__main__":
    main()
